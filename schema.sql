-- EventBook: a small ticket-booking database (all data made up)
-- Run on an empty database. Safe to re-run: it drops and recreates the tables.

DROP TABLE IF EXISTS booking_changes, reviews, bookings, events, venues, users CASCADE;

CREATE TABLE users (
    user_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    TEXT NOT NULL,
    email        TEXT NOT NULL UNIQUE,
    city         TEXT NOT NULL,
    phone        TEXT,                              -- optional, so it can be NULL
    signup_date  DATE NOT NULL,
    referred_by  INT REFERENCES users (user_id)     -- the user who invited them, NULL if nobody
);

CREATE TABLE venues (
    venue_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL UNIQUE,
    city      TEXT NOT NULL,
    capacity  INT NOT NULL CHECK (capacity > 0)
);

CREATE TABLE events (
    event_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id      INT NOT NULL REFERENCES venues (venue_id),
    title         TEXT NOT NULL,
    category      TEXT NOT NULL CHECK (category IN ('MUSIC', 'COMEDY', 'SPORTS', 'THEATER', 'FOOD')),
    event_date    DATE NOT NULL,
    ticket_price  NUMERIC(8, 2) NOT NULL CHECK (ticket_price >= 0),
    status        TEXT NOT NULL CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE bookings (
    booking_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL REFERENCES users (user_id),
    event_id    INT NOT NULL REFERENCES events (event_id),
    quantity    INT NOT NULL CHECK (quantity BETWEEN 1 AND 6),
    status      TEXT NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    booked_at   TIMESTAMP NOT NULL,
    UNIQUE (user_id, event_id)                      -- one booking per user per event
);

CREATE TABLE reviews (
    review_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INT NOT NULL REFERENCES users (user_id),
    event_id     INT NOT NULL REFERENCES events (event_id),
    rating       INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment      TEXT,                              -- optional, so it can be NULL
    reviewed_at  DATE NOT NULL,
    UNIQUE (user_id, event_id)
);

-- Audit trail: every status change on a booking is recorded here
CREATE TABLE booking_changes (
    change_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  INT NOT NULL REFERENCES bookings (booking_id),
    old_status  TEXT NOT NULL,
    new_status  TEXT NOT NULL,
    changed_at  TIMESTAMP NOT NULL DEFAULT now(),
    changed_by  TEXT NOT NULL
);
